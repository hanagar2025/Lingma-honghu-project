/**
 * 毛利率异常识别的「不可删除回归样本」。
 *
 * ── 为什么这个文件单独存在 ──
 *
 * 2026-08-16 跑同业对照时发现一个系统性陷阱:
 * **同比变化本身没有方向性含义,必须先判断基期是否异常。**
 *
 * 两家公司在同一期出现方向相同、幅度接近的同比跃升,性质却完全相反:
 *
 *   兆易创新  2025Q1 37.4% → 2026Q1 57.1%  同比 +19.6pct  ← 本期偏离自身历史
 *   拓荆科技  2025Q1 19.9% → 2026Q1 41.7%  同比 +21.8pct  ← 基期才是异常
 *
 * 只看同比的系统会把两者都判成"爆发"。而拓荆的 41.7% 其实是回到了
 * 过去 40–44% 的正常区间 —— 它是回归,不是改善。
 *
 * 真正要问的是「本期是否异常」,而不是「同比是否很大」。
 *
 * ── 为什么把样本写成常量而不是写在 selftest 里 ──
 *
 * 委员会 2026-08-16 要求这三个样本不可删除。写在 selftest 里的断言,
 * 在重写测试时会连同被删掉 —— 我这次就干过一次(上一轮的
 * 「量级异常须核验」断言在重写时被我整段替换)。
 * 单独成文件、由 selftest 引用,删它会留下 import 报错。
 *
 * 三个样本必须同时通过,任何人修改识别逻辑都要过这道门:
 *   兆易     → CURRENT_IS_OUTLIER
 *   拓荆     → BASE_IS_OUTLIER
 *   正常公司 → NO_MATERIAL_DEVIATION
 *
 * ── 数据来自真实读数,不是编的 ──
 *
 * 每个样本的季度序列都抄自 profit.json 的实际内容(见 asOf 字段)。
 * 用编的数字做回归样本,测的就只是"代码是否自洽",而不是"代码在真实数据上是否正确"。
 */

/** 一个回归样本 */
export interface GmRegressionCase {
  code: string
  name: string
  /** 判定必须等于这个值。改识别逻辑后若此处失败,先想清楚是逻辑对了还是样本过时了 */
  expect: 'CURRENT_IS_OUTLIER' | 'BASE_IS_OUTLIER' | 'BOTH_OUTLIERS' | 'NO_MATERIAL_DEVIATION'
  /** 自身历史(不含本期与基期),单位百分数 */
  history: number[]
  prevPct: number
  currentPct: number
  /** 为什么必须是这个判定 —— 写清楚,否则将来有人会以为可以放宽 */
  why: string
  asOf: string
}

